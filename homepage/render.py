def local_font_faces(style: dict) -> list[dict]:
    """Validate optional self-hosted @font-face declarations from style.yaml."""
    fonts = style.get('fonts', {})
    faces = fonts.get('local_faces', []) if isinstance(fonts, dict) else []
    if faces is None:
        return []
    if not isinstance(faces, list) or len(faces) > 8:
        raise BuildError('fonts.local_faces must be a list of at most 8 entries')
    checked = []
    for face in faces:
        if not isinstance(face, dict) or set(face) - {'family', 'file', 'weight', 'style'}:
            raise BuildError('Each fonts.local_faces entry may contain only family, file, weight, style')
        family, file = str(face.get('family', '')), str(face.get('file', ''))
        weight, fstyle = str(face.get('weight', '400')), str(face.get('style', 'normal'))
        path = PurePosixPath(file)
        if not FONT_FAMILY_RE.fullmatch(family):
            raise BuildError(f'Invalid local font family name: {family!r}')
        if (path.is_absolute() or '..' in path.parts or not file.startswith('assets/fonts/')
                or path.suffix.casefold() not in ALLOWED_FONT_EXT or not re.fullmatch(r'[\w./\-]+', file)):
            raise BuildError(f'Local fonts must be .woff2/.woff files under assets/fonts/: {file!r}')
        if not FONT_WEIGHT_RE.fullmatch(weight) or fstyle not in {'normal', 'italic'}:
            raise BuildError(f'Invalid weight or style for local font {family!r}')
        checked.append({'family': family, 'file': file, 'weight': weight, 'style': fstyle})
    return checked


def css_for(style: dict) -> str:
    colors = style.get('colors', {})
    keys = ['canvas', 'surface', 'ink', 'muted', 'border', 'accent', 'inverted', 'inverted_text', 'focus']
    if not isinstance(colors, dict) or any(not COLOR_RE.fullmatch(str(colors.get(k, ''))) for k in keys):
        raise BuildError('style.yaml colors must be six-digit hex codes')
    accent_on_dark = str(colors.get('accent_on_dark', colors['inverted_text']))
    if not COLOR_RE.fullmatch(accent_on_dark):
        raise BuildError('style.yaml colors must be six-digit hex codes')
    fonts = style.get('fonts', {})
    if not isinstance(fonts, dict):
        raise BuildError('style.yaml fonts must be a mapping')
    for fontkey in ('display', 'body', 'mono'):
        font = fonts.get(fontkey)
        if not isinstance(font, str) or len(font) > 150 or not SAFE_FONT_RE.fullmatch(font):
            raise BuildError(f'Invalid safe font list in style.yaml: {fontkey}')
    width = style.get('layout', {}).get('max_width', 1240)
    if not isinstance(width, int) or not (720 <= width <= 2000):
        raise BuildError('layout.max_width must be an integer between 720 and 2000')
    faces = '\n'.join(
        f'@font-face{{font-family:"{f["family"]}";src:url("{f["file"]}") format("{PurePosixPath(f["file"]).suffix[1:]}");'
        f'font-weight:{f["weight"]};font-style:{f["style"]};font-display:swap}}'
        for f in local_font_faces(style)
    )
    replacements = {
        '__FONT_FACES__': faces,
        '__CANVAS__': colors['canvas'], '__SURFACE__': colors['surface'], '__INK__': colors['ink'],
        '__MUTED__': colors['muted'], '__BORDER__': colors['border'], '__ACCENT__': colors['accent'],
        '__ACCENT_ON_DARK__': accent_on_dark,
        '__INVERTED__': colors['inverted'], '__INVERTED_TEXT__': colors['inverted_text'],
        '__FOCUS__': colors['focus'], '__DISPLAY_FONT__': fonts['display'],
        '__BODY_FONT__': fonts['body'], '__MONO_FONT__': fonts['mono'], '__MAX_WIDTH__': str(width),
        '__GLYPH__': str(GLYPH_SIZE),
    }
    output = CSS_TEMPLATE
    for k, v in replacements.items():
        output = output.replace(k, v)
    return output


def section_anchor(source_id: str) -> str:
    slug, occur = source_id.rsplit(':', 1)
    return slug if occur == '1' else f'{slug}--{occur}'


def image_size(path: Path) -> tuple[int, int] | None:
    """Read pixel dimensions of PNG, GIF or JPEG files without third-party libraries."""
    try:
        with path.open('rb') as fh:
            head = fh.read(32)
            if head.startswith(b'\x89PNG\r\n\x1a\n') and head[12:16] == b'IHDR':
                return struct.unpack('>II', head[16:24])
            if head[:6] in (b'GIF87a', b'GIF89a'):
                return struct.unpack('<HH', head[6:10])
            if head[:2] == b'\xff\xd8':
                fh.seek(2)
                while True:
                    marker = fh.read(2)
                    if len(marker) < 2 or marker[0] != 0xFF:
                        return None
                    while marker[1] == 0xFF:
                        marker = marker[1:] + fh.read(1)
                    code = marker[1]
                    if code in (0xD8, 0x01) or 0xD0 <= code <= 0xD7:
                        continue
                    (length,) = struct.unpack('>H', fh.read(2))
                    if 0xC0 <= code <= 0xCF and code not in (0xC4, 0xC8, 0xCC):
                        height, width = struct.unpack('>xHH', fh.read(5))
                        return width, height
                    fh.seek(length - 2, 1)
    except (OSError, struct.error):
        return None
    return None


def _validate_links_and_assets(soup: BeautifulSoup, root: Path, anchors: set[str]) -> set[Path]:
    assets: set[Path] = set()
    for tag in soup.find_all(['a', 'img']):
        attr = 'href' if tag.name == 'a' else 'src'
        ref = tag.get(attr)
        if not ref:
            if tag.name == 'img':
                raise BuildError('Markdown image has no URL')
            continue
        if any(ord(c) < 32 for c in ref) or '\\' in ref:
            raise BuildError(f'Unsafe URL in Markdown: {ref!r}')
        parts = urlsplit(ref)
        if parts.scheme in {'http', 'https', 'mailto'} and tag.name == 'a':
            if parts.scheme in {'http', 'https'} and not parts.netloc:
                raise BuildError(f'Invalid external URL: {ref}')
            continue
        if parts.scheme or parts.netloc:
            raise BuildError(f'Unsupported URL scheme or external image: {ref}')
        if tag.name == 'a' and ref.startswith('#'):
            if unquote(ref[1:]) not in anchors:
                raise BuildError(f'Broken heading anchor in content.md: {ref}')
            continue
        decoded_path = unquote(parts.path)
        # Only local files under assets are published. Fragment-only links are handled above.
        path = PurePosixPath(decoded_path)
        if path.is_absolute() or '..' in path.parts or not decoded_path.startswith('assets/'):
            raise BuildError(f'Local reference must be under assets/: {ref}')
        candidate = (root / decoded_path).resolve()
        assets_root = (root / 'assets').resolve()
        if not candidate.is_relative_to(assets_root) or not candidate.is_file() or (root / decoded_path).is_symlink():
            raise BuildError(f'Asset does not exist or escapes assets/: {ref}')
        if tag.name == 'img' and candidate.suffix.casefold() not in ALLOWED_IMAGE_EXT:
            raise BuildError(f'Unsupported image format for safe publishing: {ref}')
        if tag.name == 'img' and not str(tag.get('alt', '')).strip():
            raise BuildError(f'Every image needs meaningful alt text: {ref}')
        # Disallow HTML/JS via local linked files as well.
        if candidate.suffix.casefold() in {'.html', '.htm', '.js', '.mjs', '.svg', '.css'}:
            raise BuildError(f'Potentially executable file cannot be linked through assets/: {ref}')
        assets.add(candidate)
    return assets


def _font_assets(style: dict, root: Path) -> list[Path]:
    files = []
    assets_root = (root / 'assets').resolve()
    for face in local_font_faces(style):
        raw = root / face['file']
        candidate = raw.resolve()
        if not candidate.is_relative_to(assets_root) or not candidate.is_file() or raw.is_symlink():
            raise BuildError(f'Local font file is missing: {face["file"]} (remove it from style.yaml fonts.local_faces or add the file)')
        files.append(candidate)
    return files


def _soup(markdown_html: str) -> BeautifulSoup:
    return BeautifulSoup(markdown_html, 'html.parser')


def _markdown_html(tokens: list, engine) -> str:
    return engine.renderer.render(tokens, engine.options, {})


def _first_meaningful(node: Tag):
    for child in node.contents:
        if isinstance(child, NavigableString) and not child.strip():
            continue
        return child
    return None


def _split_lead_separator(soup: BeautifulSoup, container: Tag) -> None:
    """Hide the dash after a bold lead-in ("**Name** — text") visually; the text stays in the DOM."""
    first = _first_meaningful(container)
    if not (isinstance(first, Tag) and first.name == 'strong'):
        return
    following = first.next_sibling
    if isinstance(following, NavigableString):
        match = LEAD_SEPARATOR_RE.match(str(following))
        if match and match.group(1).strip() in {'—', '–', '-'}:
            sep = soup.new_tag('span', attrs={'class': 'lead-sep', 'aria-hidden': 'true'})
            sep.string = match.group(1)
            following.replace_with(sep)
            sep.insert_after(NavigableString(' ' + str(following)[match.end():]))


def _make_feature_grid(soup: BeautifulSoup) -> None:
    listing = soup.find('ul')
    if not listing:
        return
    entries = listing.find_all('li', recursive=False)
    grid = soup.new_tag('div', attrs={'class': 'cards'})
    for i, li in enumerate(entries, start=1):
        card = soup.new_tag('article', attrs={'class': 'card'})
        num = soup.new_tag('span', attrs={'class': 'num', 'aria-hidden': 'true'})
        num.string = f'{i:02d}'
        card.append(num)
        copy = soup.new_tag('div', attrs={'class': 'card-copy'})
        for child in list(li.contents):
            copy.append(child.extract())
        # Tight lists put text directly in <li>; loose lists wrap it in <p>.
        inner = _first_meaningful(copy)
        if isinstance(inner, Tag) and inner.name == 'p' and len([c for c in copy.contents if isinstance(c, Tag)]) == 1:
            inner.unwrap()
        _split_lead_separator(soup, copy)
        card.append(copy)
        grid.append(card)
    listing.replace_with(grid)


def _make_project_grid(soup: BeautifulSoup) -> None:
    headings = soup.find_all('h3', recursive=False)
    if not headings:
        _make_feature_grid(soup)
        return
    grid = soup.new_tag('div', attrs={'class': 'work-grid'})
    for i, heading in enumerate(headings, start=1):
        item = soup.new_tag('article', attrs={'class': 'work-item'})
        num = soup.new_tag('span', attrs={'class': 'num', 'aria-hidden': 'true'})
        num.string = f'{i:02d}'
        item.append(num)
        content = soup.new_tag('div', attrs={'class': 'work-copy'})
        # Capture sibling content until next H3 heading, preserving all Markdown blocks.
        node = heading
        while node is not None and (node is heading or not (isinstance(node, Tag) and node.name == 'h3')):
            next_node = node.next_sibling
            content.append(node.extract())
            node = next_node
        item.append(content)
        grid.append(item)
    # grid follows the introduction, which stayed in the soup.
    soup.append(grid)


def _mark_fact_lists(soup: BeautifulSoup) -> None:
    """A list whose every item starts with a bold label becomes a label/value table."""
    for listing in soup.find_all('ul'):
        items = listing.find_all('li', recursive=False)
        if len(items) < 2:
            continue
        ok = True
        for li in items:
            first = _first_meaningful(li)
            if isinstance(first, Tag) and first.name == 'p':
                first = _first_meaningful(first)
            if not (isinstance(first, Tag) and first.name == 'strong'):
                ok = False
                break
        if not ok:
            continue
        listing['class'] = listing.get('class', []) + ['facts']
        for li in items:
            first = _first_meaningful(li)
            if isinstance(first, Tag) and first.name == 'p' and len([c for c in li.contents if isinstance(c, Tag)]) == 1:
                first.unwrap()
            label = _first_meaningful(li)
            value = soup.new_tag('span', attrs={'class': 'fact-value'})
            for node in list(label.next_siblings):
                value.append(node.extract())
            li.append(value)


def _mark_actions(soup: BeautifulSoup) -> None:
    """Paragraphs made only of links (optionally separated by · | / –) render as an action row."""
    for para in soup.find_all('p'):
        links = [c for c in para.children if isinstance(c, Tag)]
        if not links or any(c.name != 'a' for c in links):
            continue
        texts = [c for c in para.children if isinstance(c, NavigableString)]
        if not all(SEPARATOR_RE.fullmatch(str(t)) for t in texts):
            continue
        para['class'] = para.get('class', []) + ['actions']
        for text in texts:
            if str(text).strip():
                sep = soup.new_tag('span', attrs={'class': 'sep', 'aria-hidden': 'true'})
                sep.string = str(text)
                text.replace_with(sep)


def _wrap_code(soup: BeautifulSoup) -> None:
    for pre in soup.find_all('pre'):
        code = pre.find('code')
        lang = ''
        for cls in (code.get('class', []) if code else []):
            if cls.startswith('language-') and CODE_LANG_RE.fullmatch(cls[9:]):
                lang = cls[9:]
        wrapper = soup.new_tag('div', attrs={'class': 'codeblock'})
        pre.wrap(wrapper)
        pre['tabindex'] = '0'
        if lang:
            label = soup.new_tag('span', attrs={'class': 'code-lang'})
            label.string = lang
            pre.insert_before(label)
            pre['aria-label'] = f'{lang} code'
        else:
            pre['aria-label'] = 'Code'


def _make_figures(soup: BeautifulSoup, root: Path) -> None:
    for img in soup.find_all('img'):
        img['loading'] = 'lazy'
        img['decoding'] = 'async'
        src = unquote(urlsplit(img.get('src', '')).path)
        if src.startswith('assets/') and '..' not in PurePosixPath(src).parts:
            size = image_size(root / src)
            if size and all(size):
                img['width'], img['height'] = str(size[0]), str(size[1])
        parent = img.parent
        if isinstance(parent, Tag) and parent.name == 'p' and all(
                c is img or (isinstance(c, NavigableString) and not c.strip()) for c in parent.contents):
            parent.name = 'figure'
            parent['class'] = ['figure']


def _wrap_tables(soup: BeautifulSoup) -> None:
    for table in soup.find_all('table'):
        wrapper = soup.new_tag('div', attrs={'class': 'table-scroll', 'role': 'region', 'tabindex': '0', 'aria-label': 'Scrollable data table'})
        table.wrap(wrapper)


def _enhance(soup: BeautifulSoup, root: Path) -> None:
    _wrap_tables(soup)
    _wrap_code(soup)
    _make_figures(soup, root)
    _mark_actions(soup)
    _mark_fact_lists(soup)


def fingerprint_glyph(digest: str) -> str:
    """Abstract, deterministic hero art: each hex digit of the content hash becomes -1, 0 or +1."""
    states = {0: 't-z', 1: 't-p', 2: 't-n'}
    cells = ''.join(f'<i class="{states[int(ch, 16) % 3]}"></i>' for ch in digest[:GLYPH_SIZE * GLYPH_SIZE])
    return f'<div class="glyph" aria-hidden="true">{cells}</div>'


def _headline_html(text: str) -> str:
    """Escape the display headline and keep hyphenated words (e.g. "1.58-bit") on one line."""
    return ' '.join(f'<span class="nobr">{esc(w)}</span>' if '-' in w[1:-1] and len(w) <= 24 else esc(w)
                    for w in text.split(' '))


def _render_hero(section, source: Source, engine, variant: str, root: Path) -> str:
    soup = _soup(_markdown_html(section.body_tokens(), engine))
    first_para = soup.find('p', recursive=False)
    headline = source.title
    if first_para:
        # Promote a standalone opening sentence to the display headline while retaining the text verbatim.
        candidate = first_para.get_text(' ', strip=True)
        if 15 <= len(candidate) <= 130 and not first_para.find(['a', 'img', 'code', 'strong', 'em']):
            headline = candidate
            first_para.extract()
    _enhance(soup, root)
    return f'''<section class="hero variant-{esc(variant)}" id="top" aria-labelledby="page-title"><div class="wrap hero-grid">
      <div class="hero-main"><h1 id="page-title">{_headline_html(headline)}</h1><div class="hero-copy">{soup}</div></div>
      {fingerprint_glyph(source.digest)}
    </div></section>'''


WIDE = {'feature_grid', 'project_showcase'}


def _render_section(section, entry: dict, engine, index: int, root: Path) -> str:
    component, variant = entry['component'], entry['variant']
    soup = _soup(_markdown_html(section.body_tokens(), engine))
    if component == 'feature_grid':
        _make_feature_grid(soup)
    elif component == 'project_showcase':
        _make_project_grid(soup)
    _enhance(soup, root)
    heading = esc(section.heading)
    anchor = esc(section_anchor(section.source_id))
    wide = component in WIDE or (component == 'image_feature' and variant == 'regular')
    classnames = ['content-section', f'section-{component}', f'variant-{variant}', 'layout-wide' if wide else 'layout-rail']
    if component == 'project_showcase':
        classnames.append('work-band')
    elif component == 'editorial_intro':
        classnames.append('editorial-intro')
    elif component == 'call_to_action':
        classnames.append('cta-band')
        classnames.append('dark' if variant == 'dark_band' else 'light')
    # Don't invent content: heading and body are always sourced exclusively from Markdown.
    return f'''<section class="{' '.join(classnames)}" id="{anchor}" aria-labelledby="heading-{anchor}">
      <div class="wrap section-grid"><header class="section-head"><span class="section-no" aria-hidden="true">{index:02d}</span>
      <h2 id="heading-{anchor}">{heading}</h2></header><div class="prose">{soup}</div></div>
    </section>'''


def render_page(source: Source, plan: dict, style: dict, root: Path, output: Path) -> None:
    css = css_for(style)
    lang = style.get('site', {}).get('language', 'en')
    if not isinstance(lang, str) or not LANG_RE.fullmatch(lang):
        raise BuildError('style.yaml site.language must be a valid BCP 47-style language tag, e.g. en or ja')
    font_files = _font_assets(style, root)
    engine = markdown_engine()
    slug_ids = {section_anchor(s.source_id) for s in source.sections}
    nav_sections = source.sections[1:5]
    nav = ''.join(f'<a href="#{esc(section_anchor(s.source_id))}">{esc(s.heading)}</a>' for s in nav_sections)
    page_chunks = []
    for i, (section, entry) in enumerate(zip(source.sections, plan['sections'])):
        if i == 0:
            page_chunks.append(_render_hero(section, source, engine, entry['variant'], root))
        else:
            page_chunks.append(_render_section(section, entry, engine, i, root))

    # Description taken only from user content, not from LLM-generated claims.
    paras = [t.content for t in source.sections[0].body_tokens() if t.type == 'inline' and t.content.strip()]
    description = re.sub(r'\s+', ' ', paras[0] if paras else source.title)
    description = re.sub(r'\[([^]]+)\]\([^)]+\)', r'\1', description)
    description = re.sub(r'[*_`]', '', description)[:160]
    faces = local_font_faces(style)
    preload = ''
    if faces:
        primary = faces[0]
        preload = f'<link rel="preload" href="./{esc(primary["file"])}" as="font" type="font/{esc(PurePosixPath(primary["file"]).suffix[1:])}" crossorigin>'
    html_doc = f'''<!doctype html>
<html lang="{esc(lang)}"><head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src 'self'; style-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'; object-src 'none'; script-src 'none'">
  <title>{esc(source.title)}</title>
  <meta name="description" content="{esc(description)}"><meta name="theme-color" content="{esc(style['colors']['canvas'])}">
  <meta property="og:type" content="website"><meta property="og:title" content="{esc(source.title)}">
  <meta property="og:description" content="{esc(description)}"><meta name="color-scheme" content="light">
  {preload}<link rel="stylesheet" href="./style.css">
</head><body>
  <a class="skip" href="#main">Skip to content</a>
  <header class="wrap site-header nav"><a class="brand" href="#top">{esc(source.title)}</a>
    <nav class="navlinks" aria-label="Sections">{nav}</nav></header>
  <main id="main">{''.join(page_chunks)}</main>
  <footer class="wrap page-footer"><span>{esc(source.title)}</span><a href="#top">Back to top</a></footer>
</body></html>
'''
    parsed = BeautifulSoup(html_doc, 'html.parser')
    copied_assets = _validate_links_and_assets(parsed, root, slug_ids | {'top', 'main'})
    copied_assets.update(font_files)
    # Additional structural checks, including accidental unsafe markup in the final document.
    if parsed.find(['script', 'iframe', 'object', 'embed', 'form']):
        raise BuildError('Unsafe active HTML detected')
    if len(parsed.find_all('h1')) != 1:
        raise BuildError('Generated page must contain exactly one H1')
    for tag in parsed.find_all(True):
        for attr in tag.attrs:
            if attr.casefold().startswith('on') or attr.casefold() == 'style':
                raise BuildError('Unsafe inline event handler or inline style detected')
    output.mkdir(parents=True, exist_ok=True)
    # To avoid stale asset files, remove and recreate the published assets folder.
    asset_output = output / 'assets'
    if asset_output.exists():
        shutil.rmtree(asset_output)
    assets_root = (root / 'assets').resolve()
    for asset in sorted(copied_assets):
        destination = asset_output / asset.relative_to(assets_root)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(asset, destination)
    # Ship font licences alongside the font files (required by the SIL OFL).
    for licence in sorted({f.parent for f in font_files}):
        for text in licence.glob('*.txt'):
            target = asset_output / text.relative_to(assets_root)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(text, target)
    (output / 'index.html').write_text(html_doc, encoding='utf-8')
    (output / 'style.css').write_text(css, encoding='utf-8')
    (output / '.nojekyll').write_text('', encoding='utf-8')


def validate_output(path: Path) -> dict:
    page = path / 'index.html'
    stylesheet = path / 'style.css'
    if not page.is_file() or not stylesheet.is_file():
        raise BuildError('Expected dist/index.html and dist/style.css')
    parsed = BeautifulSoup(page.read_text(encoding='utf-8'), 'html.parser')
    if len(parsed.find_all('h1')) != 1 or not parsed.find('main') or not parsed.find('nav'):
        raise BuildError('Generated output missing semantic structure')
    if parsed.find(['script', 'iframe', 'object', 'embed', 'form']):
        raise BuildError('Generated output includes forbidden executable elements')
    anchors = {tag['id'] for tag in parsed.find_all(id=True)}
    for link in parsed.find_all('a', href=True):
        href = link['href']
        if href.startswith('#') and unquote(href[1:]) not in anchors:
            raise BuildError(f'Generated page has broken anchor: {href}')
    for tag in parsed.find_all(True):
        for attr in tag.attrs:
            if attr.lower().startswith('on'):
                raise BuildError('Generated output has an inline event handler')
    # Every local file the page or stylesheet references must actually be published.
    refs = [img.get('src', '') for img in parsed.find_all('img')]
    refs += [link.get('href', '') for link in parsed.find_all('link', href=True)]
    refs += re.findall(r'url\("?([^")]+)"?\)', stylesheet.read_text(encoding='utf-8'))
    for ref in refs:
        parts = urlsplit(ref)
        if parts.scheme or parts.netloc:
            continue
        target = (path / unquote(parts.path)).resolve()
        if not target.is_relative_to(path.resolve()) or not target.is_file():
            raise BuildError(f'Generated output references a missing file: {ref}')
    return {'title': parsed.title.get_text() if parsed.title else '', 'h1': ' '.join(parsed.h1.get_text(' ', strip=True).split()),
            'sections': len(parsed.select('main > section')), 'bytes': page.stat().st_size}
